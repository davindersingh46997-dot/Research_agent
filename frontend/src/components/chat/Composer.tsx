import { type FormEvent, type KeyboardEvent, type RefObject } from 'react';
import { ArrowUpRight, Cpu, Square } from 'lucide-react';

interface ComposerProps {
  draft: string;
  setDraft: (value: string) => void;
  onSubmit: () => void;
  loading: boolean;
  onStop: () => void;
  inputRef: RefObject<HTMLTextAreaElement>;
}

export function Composer({
  draft,
  setDraft,
  onSubmit,
  loading,
  onStop,
  inputRef,
}: ComposerProps) {
  const handleSubmit = (e?: FormEvent) => {
    if (e) e.preventDefault();
    if (!draft.trim() || loading) return;
    onSubmit();
  };

  const handleKeyDown = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === 'Enter' && !e.shiftKey) {
      e.preventDefault();
      handleSubmit();
    }
  };

  return (
    <footer className="composer-area">
      <form className="composer" onSubmit={handleSubmit}>
        <textarea
          ref={inputRef}
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
          onKeyDown={handleKeyDown}
          placeholder="Type a research question for the OpenRouter model..."
          aria-label="Chat input"
          rows={2}
          disabled={loading}
        />

        <div className="composer-controls">
          <span className="composer-hint">
            <span className="composer-lock">
              <Cpu size={12} />
            </span>{' '}
            Model configured in OPENROUTER_MODEL
          </span>
          <div className="composer-actions">
            <span className="keyboard-hint">Enter to send · Shift + Enter for new line</span>
            <button
              className="send-button"
              type={loading ? 'button' : 'submit'}
              onClick={loading ? onStop : undefined}
              disabled={!loading && !draft.trim()}
              aria-label={loading ? 'Stop generating' : 'Send message'}
              title={loading ? 'Stop generating' : 'Send message'}
            >
              {loading ? (
                <Square size={14} fill="currentColor" />
              ) : (
                <ArrowUpRight size={19} />
              )}
            </button>
          </div>
        </div>
      </form>

      <p className="disclaimer">
        Responses are generated by the model selected in OPENROUTER_MODEL. Keep your OPENROUTER_API_KEY in the root .env file.
      </p>
    </footer>
  );
}
